/**
 * מספר טלפון ישראלי · תמיד בפורמט `050-0000000`.
 *
 * שקד ביקשה (16 בספטמבר 2026) שכל צורת הקלדה תתוקן אוטומטית לפורמט
 * הזה. ההפרדה לשתי פונקציות היא כדי לא להילחם באצבע:
 *
 * · `maskPhone` רץ **בכל תו** ורק מכניס מקף. הוא לעולם לא מוסיף
 *   ספרה, אחרת הקלדת ״5״ הייתה קופצת ל-״05״ והסמן היה בורח.
 * · `normalizePhone` רץ **כשיוצאים מהשדה** ומתקן גם קידומת בינלאומית
 *   וגם אפס חסר.
 *
 * ⚠ **המקף אינו תמיד אחרי שלוש ספרות** · ניידים הם `05X` ולכן
 * `050-2958511`, אבל קווי חייג הם קידומת בת שתיים — `08-9433333`.
 * אותה הבחנה קיימת כבר ב-`okPhone` שבמסך ההתחברות.
 */

/** אורך הקידומת · 3 בנייד, 2 בקו נייח */
const headOf = (digits: string): number => (digits.startsWith('05') ? 3 : 2);

/** כמה ספרות אחרי הקידומת */
const TAIL = 7;

const digitsOf = (raw: string): string => raw.replace(/\D/g, '');

/**
 * שתילת המקף.
 * ⚠ `cap` הוא **קריטי** · נמדד בדפדפן (16 בספטמבר 2026): כשהמסכה
 * החיה קיצצה ל-7 ספרות אחרי הקידומת, הדבקה של `+972-50-295-8511`
 * יצאה `97-2502958` — הספרות האחרונות נמחקו לפני שהנרמול הספיק
 * לראות אותן, ולא הייתה שום דרך לשחזר. לכן המסכה החיה **אינה
 * מקצצת**, והקיצוץ קורה רק בנרמול שביציאה מהשדה.
 */
const dash = (d: string, cap: boolean): string => {
  const head = headOf(d);
  if (d.length <= head) return d;
  return `${d.slice(0, head)}-${cap ? d.slice(head, head + TAIL) : d.slice(head)}`;
};

/** מסכה חיה · מכניסה מקף בלבד, בלי להוסיף, להשלים או לקצץ ספרות */
export function maskPhone(raw: string): string {
  const d = digitsOf(raw);
  return d === '' ? '' : dash(d, false);
}

/**
 * נרמול מלא · קידומת בינלאומית ואפס חסר.
 * `+972-50-295-8511`, `972502958511`, `502958511` → `050-2958511`
 */
export function normalizePhone(raw: string): string {
  let d = digitsOf(raw);
  if (d === '') return '';
  if (d.startsWith('00972')) d = d.slice(5);
  else if (d.startsWith('972')) d = d.slice(3);
  /* ⚠ האפס מושלם רק כשהמספר כבר שלם · באמצע הקלדה זה היה מקפיץ ספרות */
  if (!d.startsWith('0') && d.length >= 9) d = `0${d}`;
  return dash(d, true);
}

/**
 * האם זה מספר טלפון ישראלי תקין.
 *
 * ⚠ אותו כלל בדיוק של `okPhone` במסך ההתחברות · נייד `05X` או
 * קידומת בת שתיים, ואחריהן שבע ספרות. מוגדר כאן כדי שיהיה מקור
 * אחד לכל המקומות שבודקים טלפון.
 */
export const isPhone = (raw: string): boolean =>
  /^0(5\d|[2-489])-?\d{7}$/.test(raw.trim().replace(/\s/g, ''));

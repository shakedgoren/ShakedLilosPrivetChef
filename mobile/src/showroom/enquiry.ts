export const BUSINESS_WA = '972525056708';

/** תווית ״אין תשובה״ · אותו קו מפריד שבעמוד הנחיתה */
const BLANK = '—';

/** ⚠ סוגי האירועים · נכתבו על ידי Claude, כמו בעמוד הנחיתה */
export const EVENT_KINDS = [
  'יום הולדת',
  'ברית · בריתה',
  'בר · בת מצווה',
  'חתונה',
  'אירוח בבית',
  'אירוע חברה',
  'מסיבת רווקים/ות',
  'הפרשת חלה',
  'אחר',
] as const;

/** מה שהטופס אוסף · אותם שדות בדיוק כמו בעמוד הנחיתה */
export type Enquiry = {
  name: string;
  phone: string;
  kind: string;
  date: string;
  guests: string;
  note: string;
};

export const EMPTY_ENQUIRY: Enquiry = {
  name: '',
  phone: '',
  kind: '',
  date: '',
  guests: '',
  note: '',
};

/**
 * מה חסם את השליחה · `null` כשהטופס מוכן.
 *
 * ⚠ **שם וטלפון בלבד הם חובה** · בדיוק כמו `sendEvent` בעמוד
 * הנחיתה, שמחזיר `false` ומעביר פוקוס לשדה החסר. כל השאר יוצא
 * כ-״—״ בהודעה, כי אירוע שעוד לא תוכנן הוא בדיוק המצב שבו
 * אנשים משאירים פרטים.
 */
export function enquiryMissing(v: Enquiry): keyof Enquiry | null {
  if (!v.name.trim()) return 'name';
  if (!v.phone.trim()) return 'phone';
  return null;
}

/**
 * הודעת הוואטסאפ.
 *
 * ⚠ **הסדר והכותרות של שקד · אין לשנות** · ראו הפתק בראש הקובץ.
 * השורה הריקה השנייה היא חלק מהנוסח ולא תקלה בעימוד.
 */
export function enquiryMessage(v: Enquiry): string {
  const or = (s: string) => s.trim() || BLANK;
  return [
    'היי שקד, אני מעוניין/ת לתכנן אירוע עם BITE & TELL.',
    '',
    'שם: ' + v.name.trim(),
    'טלפון: ' + v.phone.trim(),
    'סוג האירוע: ' + or(v.kind),
    'תאריך: ' + or(v.date),
    'מספר אורחים: ' + or(v.guests),
    'פרטים נוספים: ' + or(v.note),
  ].join('\n');
}

/** הקישור המלא · wa.me עם ההודעה מקודדת */
export function enquiryLink(v: Enquiry): string {
  return `https://wa.me/${BUSINESS_WA}?text=${encodeURIComponent(enquiryMessage(v))}`;
}

const BOARD_PREP: Readonly<Record<string, readonly [string, string]>> = {
  thin: ['שניצל דק', 'חלה'],
  temp: ['שניצל טמפורה', 'חלה'],
  boxThin: ['שניצל דק', 'מארז'],
  boxTemp: ['שניצל טמפורה', 'מארז'],
};

/** שתי שורות הכרית · מזהה שאינו בטבלה מקבל את השם בשורה אחת */

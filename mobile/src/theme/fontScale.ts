export const FONT_BUMP: number = 4;

/** הגדלים שהוצגו לה · 0 הוא המצב הנוכחי */
export const FONT_BUMP_STEPS = [0, 2, 4, 6, 8, 10] as const;

/**
 * כמה **גדל** גוש כותרת מרחף בגלל ההגדלה.
 *
 * ⚠ **נבנה ב-17 בספטמבר 2026** · שקד: ״בגלל שהגדלנו את הכיתובים
 * צריך להוסיף בכל הכותרות הפנימיות של הספיישל מעט רווח למטה שלא
 * ייחתך המחיר, גם במגשי פירות״.
 *
 * גוש הכותרת בכל מסך קטגוריה מרחף מעל אזור הגלילה, והריפוד העליון
 * של אזור הגלילה הוא שמרחיק את התוכן ממנו. הריפודים האלה נמדדו
 * כשהכתב היה קטן יותר, ולכן ההגדלה בלעה בדיוק את הרווח שמתחת
 * למחיר. כאן מחזירים אותו — לא מספר חדש, אלא בדיוק מה שגדל.
 *
 * `lines` הוא מספר השורות שמתחת לכותרת (תאריך, שעות, מחיר).
 */
export const headRoom = (lines = 1): number => FONT_BUMP * (1 + lines);


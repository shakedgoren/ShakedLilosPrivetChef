import { BOXES, type Box } from '../../data/boxes';

/**
 * מי מוצג ברשימת הספיישלים, ומי יושב בתוך מארז אחר.
 *
 * ⚠ **שכבת הרחבה · לא `boxes.ts`** · אותו קובץ נחצב אוטומטית
 * מ-Boxes.dc.html בקנבס (`scripts/extract-boxes.mjs`) ואין לערוך
 * אותו ביד — עריכה שם נמחקת בחציבה הבאה. כל החלטה על **סידור**
 * המארזים יושבת כאן.
 *
 * ⚠ **קובץ בלי React · בכוונה** · כך `server/npm test` יכול לייבא
 * אותו ולשמור על הכללים, בדיוק כמו `passwordRule` ו-`dateRule`.
 */

/**
 * מארזים שלא מוצגים באתר · שקד ביקשה להוריד את מארז הפרימיום.
 * הנתונים נשארים ב-`boxes.ts` כדי שאפשר יהיה להחזיר אותו בשורה אחת.
 */
export const HIDDEN: readonly string[] = ['premium'];

/**
 * מארז שיושב **בתוך** מארז אחר · מפתח → מפתח ההורה.
 *
 * ⚠ **בקשת שקד · 26 בספטמבר 2026** · ״יש צורך את ׳טעם של שנה
 * טובה׳ להעביר לתוך ׳חלה לכל אירוע׳״.
 *
 * ⚠ **מה שהשתנה הוא המקום, לא המארז** · ״טעם של שנה טובה״ ירד
 * מרשימת הספיישלים ונפתח מתוך מסך ״חלה לכל אירוע״. המסך שלו,
 * המחיר שלו (49 ש״ח) והנוסחים שלו לא נגעו בהם, והשרת ממשיך לתמחר
 * אותו דרך `BOXES` המלא.
 *
 * ⚠ **לא מיזוג · ובכוונה** · אפשר לקרוא את הבקשה גם כ״שנה טובה
 * הופך לסוג אירוע בתוך חלה לכל אירוע״. זה היה משנה את המחיר
 * מ-49 ש״ח למארז ל-20 ש״ח ליחידה במינימום 25 יחידות — כלומר
 * להמציא מחיר ולמחוק מוצר. אם זו הכוונה, זו בקשה נפרדת.
 */
export const NESTED: Readonly<Record<string, string>> = { shana: 'challah' };

/** מה שמוצג ברשימת הספיישלים · בלי המוסתרים ובלי המקוננים */
export const LISTED_BOXES: Box[] = BOXES.filter(
  (b) => !HIDDEN.includes(b.key) && !NESTED[b.key],
);

/** המארזים שיושבים בתוך המארז הזה · הכרטיס שבתוך המסך */
export const childrenOf = (key: string): Box[] =>
  BOXES.filter((b) => NESTED[b.key] === key && !HIDDEN.includes(b.key));

/** ההורה של מארז מקונן · `undefined` למארז רגיל */
export const parentOf = (key: string): string | undefined => NESTED[key];

/** האם המארז הזה קיים בכלל · בלי לבדוק איפה הוא מוצג */
export const boxExists = (key: string): boolean => BOXES.some((b) => b.key === key);

/**
 * האם ״להזמין שוב״ יכול לפתוח את המארז הזה.
 *
 * ⚠ **מקונן ≠ מוסתר** · מארז שעבר לתוך מארז אחר עדיין נמכר, ולכן
 * הזמנה ישנה שלו **כן** נפתחת. מארז שהוסתר לא. קודם שתי המילים
 * האלה היו אותה בדיקה, ומארז מקונן היה נשאר ללא תגובה.
 */
export const canReopen = (key: string): boolean => boxExists(key) && !HIDDEN.includes(key);

/** `count(1,'הזמנה אחת','הזמנות')` → ״הזמנה אחת״ · `count(3,…)` → ״3 הזמנות״ */
export const count = (n: number, one: string, many: string): string =>
  n === 1 ? one : `${n} ${many}`;

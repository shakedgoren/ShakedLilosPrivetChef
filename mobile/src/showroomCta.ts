type Listener = () => void;

const listeners = new Set<Listener>();

/** השורש נרשם · מחזיר פונקציית ביטול */
export function onShowroomRequest(fn: Listener): () => void {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

/** נקרא מהכפתור · מכריז בלבד, לא מנווט */
export function onShowroomCta(): void {
  if (listeners.size === 0) {
    /* ⚠ לא נבלע בשקט · כפתור שלא עושה כלום הוא באג, לא עיצוב */
    console.warn('[גרסת ראווה] נלחץ ״להזמנה״ ואין מי שיפתח את רשימת ההמתנה');
    return;
  }
  listeners.forEach((fn) => fn());
}

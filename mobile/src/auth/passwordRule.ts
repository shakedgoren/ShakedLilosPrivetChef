/** אורך מינימלי · הדרישה של שקד */
export const PASS_MIN = 8;

/** מה חסר בסיסמה · רשימה ריקה = תקינה */
export function passwordProblems(pass: string): string[] {
  const out: string[] = [];
  if (pass.length < PASS_MIN) out.push(`לפחות ${PASS_MIN} תווים`);
  if (!/[A-Z]/.test(pass)) out.push('אות גדולה באנגלית');
  if (!/[a-z]/.test(pass)) out.push('אות קטנה באנגלית');
  if (!/[0-9]/.test(pass)) out.push('ספרה אחת');
  return out;
}

/** האם הסיסמה עומדת בכל הדרישות */
export function isStrongPassword(pass: string): boolean {
  return passwordProblems(pass).length === 0;
}


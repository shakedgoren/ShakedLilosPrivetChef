import { z } from 'zod';

/**
 * גוף הבקשה של `POST /auth/login`.
 *
 * ⚠ **למה זה קובץ נפרד · 3 באוקטובר 2026** · הסכמה ישבה בתוך
 * `routes/auth.ts`, שמייבא את prisma ואת כל שאר השרת, ולכן אי
 * אפשר היה לבדוק אותה בלי להרים מסד. אותה סיבה בדיוק שבגללה
 * `passwordRule`, `phoneLock` ו-`dateRule` יושבים בקבצים משלהם.
 *
 * ⚠ **הבאג שהקובץ הזה נולד ממנו** · `/login` השתמש ב-
 * `whoBody.pick({ who, password })`, ושם `password` הוא
 * `strongPassword`. כלומר השרת **פסל סיסמה חלשה בכניסה**, בשלב
 * הוולידציה, לפני שבכלל השווה אותה ל-hash. כל חשבון שנוצר לפני
 * כלל הסיסמה של 26 בספטמבר ננעל בחוץ — שקד דיווחה על שני
 * החשבונות שלה, ואפילו ההודעה שחזרה לא אמרה ״סיסמה שגויה״.
 *
 * ⚠ **הכלל שלא נשבר שוב** · מדיניות סיסמה חלה על **יצירה** —
 * הרשמה, שינוי סיסמה, איפוס. על **אימות** היא לא חלה לעולם: מי
 * שיש לו כבר סיסמה חלשה חייב להצליח להיכנס כדי שיוכל להחליף
 * אותה. כאן נבדק רק שהשדה אינו ריק.
 */
export const loginBody = z.object({
  who: z.string().min(3),
  password: z.string().min(1),
});

export type LoginBody = z.infer<typeof loginBody>;

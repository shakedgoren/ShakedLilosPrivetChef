export type SignupWho = { kind: 'email'; email: string } | { kind: 'phone'; phone: string };

export function signupEmail(who: SignupWho, typed: string | null, taken: boolean): string | null {
  if (who.kind === 'email') return who.email;
  const mail = (typed ?? '').trim();
  if (!mail) return null;
  return taken ? null : mail;
}

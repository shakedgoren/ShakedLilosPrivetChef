/**
 * המכסה של כל מנה ביום מכירה · **מקור אחד לכל המסכים**.
 *
 * ⚠ **נבנה ב-19 בספטמבר 2026** · שקד דיווחה: ״בטבלה של ההזמנות
 * במכירה זה מציג נתונים לא נכונים, 0 מתוך 0. נכון אומנם שאין אף
 * הזמנה במערכת, אבל כן יש במלאי כמות של מנות שהיא שונה מ-0״.
 *
 * היא צודקת, ושני המסכים באמת לא הסכימו: דף **המלאי** נפל למכסת
 * יום המכירה (`d.q`) כשלא הוזנה מכסה, ואילו **לוח ההזמנות** נפל
 * ל-0 — שינוי שנעשה יום קודם אחרי שדיווחה על ״100 מתוך 100״.
 * התוצאה הייתה מספר אחד בדף המלאי ואפס בלוח, לאותו יום עצמו.
 *
 * ⚠ **0 אינו ״חסר״** · `??` ולא `||`, כדי שמכסה שהוזנה במפורש
 * כאפס (מנה שלא מכינים היום) לא תיפול בחזרה לברירת המחדל.
 *
 * ⚠ **רק מנות הקטגוריה** · מזהים שנשמרו ואינם שייכים ליום הזה
 * אינם נכנסים לתשובה, כדי ששינוי תפריט לא יגרור מכסות יתומות.
 */
export type QuotaDish = { id: string; q: number };

export function dayQuotas(
  dishes: readonly QuotaDish[],
  saved: Readonly<Record<string, number>>,
): Record<string, number> {
  return Object.fromEntries(dishes.map((d) => [d.id, saved[d.id] ?? d.q]));
}
